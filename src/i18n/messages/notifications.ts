export type NotificationLang = keyof typeof notificationMessages;

/** Title and text of a notification in one language ({name} placeholders filled from params) */
export function renderNotification(lang: NotificationLang, type: NotificationType, params: Record<string, string | number> = {}) {
  const m = (notificationMessages[lang] || notificationMessages.en) as Record<string, string>;
  const fill = (s: string) => s.replace(/\{(\w+)\}/g, (_, k) => (params[k] === undefined ? '' : String(params[k]))).replace(/\s+([.!?])$/, '$1').trim();
  return { title: fill(m[`${type}_title`] || type), body: fill(m[`${type}_body`] || '') };
}
